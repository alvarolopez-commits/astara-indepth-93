    ok = norm(en[f"chapter.s{n}.title"]).replace(" ?", "?") == h.replace(" ?", "?")
    print(f"heading {n}:", "OK" if ok else f"DIFFERS | {norm(en[f'chapter.s{n}.title'])!r} vs {h!r}")
    if not ok: fail.append(f"heading {n}")
