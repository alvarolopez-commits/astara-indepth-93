# ---- fill the English the page ships with (the browser re-writes it in the chosen language) ----
count = {"filled": 0}
def fill(m):
    tag, attrs, key = m.group(1), m.group(2), m.group(3)
    args = json.loads(H.unescape(re.search(r"data-i18n-args='([^']*)'", attrs).group(1))) if "data-i18n-args=" in attrs else None
    fm = re.search(r'data-i18n-fmt="(\w+)"', attrs)
    count["filled"] += 1
    return f"<{tag}{attrs}>{I18.render(en, key, args, fm.group(1) if fm else None)}</{tag}>"
body = re.sub(r'<(\w+)(\s[^>]*?\bdata-i18n="([^"]+)"[^>]*)>(?=</\1>)</\1>', fill, body)
n_marked = len(re.findall(r'\bdata-i18n="', body))
if count["filled"] != n_marked: fail.append(f"{n_marked - count['filled']} data-i18n elements are not empty in the template (they must hold no text)")
def fill_attrs(m):
    tag = m.group(0)
    for part in re.search(r'data-i18n-attr="([^"]+)"', tag).group(1).split(";"):
        a, k = part.split(":", 1)
        tag, n = re.subn(rf'(\s{re.escape(a)}=)""', lambda x: f'{x.group(1)}"{H.escape(en[k])}"', tag, count=1)
        if not n: fail.append(f"data-i18n-attr {a}:{k}: the element needs an empty {a}=\"\" to fill")
    return tag
body = re.sub(r"<[^>]*\bdata-i18n-attr=\"[^\"]+\"[^>]*>", fill_attrs, body)

